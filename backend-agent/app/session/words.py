ALL: tuple[str, ...] = tuple(w for ws in DEFAULTS.values() for w in ws)


def key(w: str) -> str:
    """띄어쓰기만 다른 낱말은 같은 카드로 본다 (화면의 wordKey 와 같다)."""
    return re.sub(r"\s+", "", w or "")


_BY_KEY = {key(w): w for w in ALL}


def allowed(raw: str, link_topic: str) -> str | None:
    """
    고른 낱말이 카드에 있으면 **카드의 글자 그대로** 돌려준다. 없으면 None.

    링크의 구체 주제는 자녀가 적은 그대로 돌려준다. 띄어쓰기는 보지 않는다 —
    「첫직장」 을 보내도 카드의 「첫 직장」 으로 연다. 보낸 글자를 그대로 쓰지 않는 것은
    이 함수를 지난 글이 늘 목록 안의 글이게 하려는 것이다.
    """
    k = key(raw)
    if not k:
        return None
    if link_topic and k == key(link_topic):
        return link_topic
    return _BY_KEY.get(k)
