-- 004 — 사진의 단서를 사진에 붙인다
--
-- 단서는 session.photo_clues 에만 있었다. 회차가 열려야 생기는 자리라 분석도
-- 회차를 열 때 시작할 수밖에 없었고, 분석은 1.6~3.9초가 걸린다. 여는 말에는
-- 그 시간이 숨을 T2 침묵이 없어서 첫 마디는 사진을 보지 않은 고정 문장이었다.
-- §2 가 만들어 둔 사진 질문은 한 턴을 놀린 뒤에야 쓰였다.
--
-- 사진은 시작 단추보다 **먼저** 올라온다 — 고르고, 보고, 그다음에 시작을
-- 누르신다. 올릴 때 분석해 여기 적어 두면 회차가 열리는 순간 단서가 이미 있고,
-- 여는 말부터 §2 의 질문으로 열 수 있다.
--
-- session.photo_clues 는 그대로 둔다. 그쪽은 「이 회차가 무엇을 보고 물었는가」의
-- 기록이고 이쪽은 「이 사진이 무엇을 담았는가」의 기록이다. 한 사진을 여러
-- 회차에서 쓰면 뒤쪽은 한 번만 계산된다.
--
-- (003 주석의 「004 에서 elder 로 묶는다」는 다음 번호로 밀린다.)

ALTER TABLE photo ADD COLUMN IF NOT EXISTS clues JSONB;

COMMENT ON COLUMN photo.clues IS
  '§2 사진 분석 결과. 사진당 한 번 계산해 회차마다 재사용한다. NULL 은 아직 없거나 분석이 실패한 것이다';
